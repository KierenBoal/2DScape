package com.kierenboal.npcsnap.targeting;

public final class BoatTileFace
{
	public final float x0;
	public final float y0;
	public final float z0;
	public final float x1;
	public final float y1;
	public final float z1;
	public final float x2;
	public final float y2;
	public final float z2;
	public final int colorA;
	public final int colorB;
	public final int colorC;

	public BoatTileFace(float x0, float y0, float z0, float x1, float y1, float z1,
		float x2, float y2, float z2, int colorA, int colorB, int colorC)
	{
		this.x0 = x0;
		this.y0 = y0;
		this.z0 = z0;
		this.x1 = x1;
		this.y1 = y1;
		this.z1 = z1;
		this.x2 = x2;
		this.y2 = y2;
		this.z2 = z2;
		this.colorA = colorA;
		this.colorB = colorB;
		this.colorC = colorC;
	}
}
