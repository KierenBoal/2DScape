package com.kierenboal.npcsnap;

final class TextureUvs
{
	final float u0;
	final float v0;
	final float u1;
	final float v1;
	final float u2;
	final float v2;

	TextureUvs(float u0, float v0, float u1, float v1, float u2, float v2)
	{
		this.u0 = u0;
		this.v0 = v0;
		this.u1 = u1;
		this.v1 = v1;
		this.u2 = u2;
		this.v2 = v2;
	}
}

